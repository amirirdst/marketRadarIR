
# -*- coding: utf-8 -*-

import asyncio
from prices import build_report
from telegram_bot import send_report


# =========================================================
# تنظیمات
# =========================================================

SEND_INTERVAL = 600  # 10 دقیقه = 600 ثانیه


# =========================================================
# ارسال یک گزارش تازه
# =========================================================

async def send_fresh_report():
    print("\n" + "=" * 60)
    print("🔄 دریافت قیمت‌های جدید...")

    try:
        # مهم:
        # این تابع هر بار دوباره TGJU و Nobitex را صدا می‌زند
        # و گزارش جدید می‌سازد.
        report = build_report()

        print(report)

        print("\n📤 در حال ارسال گزارش جدید به تلگرام...")

        await send_report(report)

        print("✅ گزارش با موفقیت به تلگرام ارسال شد.")

    except Exception as e:
        print(f"❌ خطا در دریافت یا ارسال گزارش: {e}")


# =========================================================
# اجرای دائمی ربات
# =========================================================

async def main():

    print("🚀 Market Radar IR شروع شد.")
    print("⏱ ارسال خودکار هر ۱۰ دقیقه فعال است.")

    while True:

        # ---------------------------------------------
        # هر بار گزارش کاملاً جدید ساخته می‌شود
        # ---------------------------------------------

        await send_fresh_report()

        # ---------------------------------------------
        # ۱۰ دقیقه تا دریافت و ارسال بعدی
        # ---------------------------------------------

        print("\n⏳ گزارش بعدی ۱۰ دقیقه دیگر ارسال می‌شود...")

        await asyncio.sleep(SEND_INTERVAL)


# =========================================================
# شروع برنامه
# =========================================================

if __name__ == "__main__":
    try:
        asyncio.run(main())

    except KeyboardInterrupt:
        print("\n🛑 ربات توسط کاربر متوقف شد.")

